-- ─────────────────────── wrapper do botão "Gerar lançamentos" ───────────────────────
create or replace function public.parceiro_lancar_instalacao_admin(p_venda uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if coalesce(public.meu_perfil(), '') <> 'admin' then
    raise exception 'Só o admin gera os lançamentos do parceiro.' using errcode = '42501';
  end if;
  return public.parceiro_lancar_instalacao(p_venda);
end;
$$;
revoke execute on function public.parceiro_lancar_instalacao_admin(uuid) from public, anon;
grant execute on function public.parceiro_lancar_instalacao_admin(uuid) to authenticated;
